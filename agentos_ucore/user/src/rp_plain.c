#define ARRAY_LEN(a) ((int)(sizeof(a) / sizeof((a)[0])))

static int contains(const char *text, const char *needle) {
    if (needle == 0 || needle[0] == 0) return 1;
    int n = (int)strlen(needle);
    int m = (int)strlen(text);
    if (n > m) return 0;
    for (int i = 0; i <= m - n; i++) {
        int same = 1;
        for (int j = 0; j < n; j++) {
            if (text[i + j] != needle[j]) {
                same = 0;
                break;
            }
        }
        if (same) return 1;
    }
    return 0;
}

static int sum_objects(void) { int total = 0; for (int i = 0; i < ARRAY_LEN(OBJECTS); i++) total += OBJECTS[i].count; return total; }
static int sum_feature_units(void) { int total = 0; for (int i = 0; i < ARRAY_LEN(FEATURES); i++) total += FEATURES[i].capability_units; return total; }

static int check_catalog(void) {
    int bad = 0;
    if (ARRAY_LEN(OBJECTS) < 450) bad++;
    if (ARRAY_LEN(SERVICES) < 100) bad++;
    if (ARRAY_LEN(FEATURES) < 25) bad++;
    if (sum_objects() < 1000) bad++;
    return bad == 0;
}

static int run_checks(void) {
    int ok = 0;
    for (int i = 0; i < ARRAY_LEN(CHECKS); i++) {
        if (strcmp(CHECKS[i].status, "ok") == 0) ok++;
    }
    return ok == ARRAY_LEN(CHECKS);
}

static int verify_mature_capability(void) {
    int target_ok = 0;
    for (int i = 0; i < ARRAY_LEN(MAPPINGS); i++) {
        if (MAPPINGS[i].target_ratio_x100 >= 30) target_ok++;
    }
    return ARRAY_LEN(REFERENCES) >= 6 && ARRAY_LEN(MAPPINGS) >= 6 && target_ok == ARRAY_LEN(MAPPINGS);
}

static int simulate_research_run(void) {
    int failures = 0;
    for (int i = 0; i < ARRAY_LEN(TASKS); i++) TASKS[i].done = 1;
    for (int i = 0; i < ARRAY_LEN(STAGES); i++) {
        if (STAGES[i].status < 0) { failures++; STAGES[i].status = 1; }
    }
    int done = 0;
    for (int i = 0; i < ARRAY_LEN(TASKS); i++) if (TASKS[i].done) done++;
    return failures == 1 && done == ARRAY_LEN(TASKS);
}

static int search_catalog(const char *needle) {
    int hits = 0;
    for (int i = 0; i < ARRAY_LEN(OBJECTS); i++) if (contains(OBJECTS[i].name, needle)) hits++;
    for (int i = 0; i < ARRAY_LEN(SERVICES); i++) if (contains(SERVICES[i], needle)) hits++;
    for (int i = 0; i < ARRAY_LEN(FEATURES); i++) if (contains(FEATURES[i].name, needle) || contains(FEATURES[i].description, needle)) hits++;
    return hits;
}

static void print_summary(void) {
    printf("rp_plain summary\n");
    printf("objects=%d object_total=%d services=%d features=%d feature_units=%d checks=%d references=%d mappings=%d\n",
           ARRAY_LEN(OBJECTS), sum_objects(), ARRAY_LEN(SERVICES), ARRAY_LEN(FEATURES), sum_feature_units(), ARRAY_LEN(CHECKS), ARRAY_LEN(REFERENCES), ARRAY_LEN(MAPPINGS));
    printf("search workflow=%d agent=%d evidence=%d provenance=%d llm=%d\n",
           search_catalog("workflow"), search_catalog("agent"), search_catalog("evidence"), search_catalog("provenance"), search_catalog("llm"));
    printf("reference platforms:");
    for (int i = 0; i < ARRAY_LEN(REFERENCES); i++) printf(" %s", REFERENCES[i].name);
    printf("\n");
}

static int selftest(void) {
    int ok_catalog = check_catalog();
    int ok_checks = run_checks();
    int ok_mature = verify_mature_capability();
    int ok_run = simulate_research_run();
    int ok_search = search_catalog("workflow") >= 10 && search_catalog("agent") >= 10 && search_catalog("evidence") >= 3;
    printf("catalog_ok=%d checks_ok=%d mature_ok=%d run_ok=%d search_ok=%d\n", ok_catalog, ok_checks, ok_mature, ok_run, ok_search);
    return ok_catalog && ok_checks && ok_mature && ok_run && ok_search;
}

int main(int argc, char **argv) {
    (void)argc; (void)argv;
    print_summary();
    int ok = selftest();
    if (!ok) {
        printf("rp_plain: failed\n");
        return 1;
    }
    printf("rp_plain: passed\n");
    return 0;
}
